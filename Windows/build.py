"""Build the Windows x64 app, uninstaller and single-file installer. Python 3.9+."""
import hashlib,json,os,pathlib,shutil,subprocess,zipfile

root=pathlib.Path(__file__).resolve().parent
build=root/'Build';build.mkdir(exist_ok=True)
dotnet=os.environ.get('DOTNET_EXE') or shutil.which('dotnet') or str(root/'Dependencies/dotnet/dotnet')
node=os.environ.get('NODE_EXE') or shutil.which('node')
env=dict(os.environ,DOTNET_CLI_HOME=str(build/'dotnet-home'),NUGET_PACKAGES=str(build/'packages'),
         DOTNET_CLI_TELEMETRY_OPTOUT='1',DOTNET_GENERATE_ASPNET_CERTIFICATE='false',DOTNET_NOLOGO='1')
def run(args,cwd=root):subprocess.run([str(a) for a in args],cwd=cwd,env=env,check=True)
def compile(project,output,*props):
 run([dotnet,'restore',project,'--locked-mode','--nologo',*props])
 run([dotnet,'build',project,'-c','Release','-o',output,'--no-restore','--nologo',*props])
def digest(path):return hashlib.sha256(path.read_bytes()).hexdigest()

# Do not silently accept different upstream executables on a later build.
lock=json.loads((root/'Dependencies/downloads.lock.json').read_text())
for name in ['ffmpeg-7.1.1.zip','MicrosoftEdgeWebview2Setup.exe']:
 path=root/'Dependencies'/name
 if digest(path)!=lock[name]['hash']:raise RuntimeError('Dependency checksum mismatch: '+name)
if not node:raise RuntimeError('Node.js required to rebuild the shared React interface.')
run([node,'build.mjs'],root/'UI')
compile(root/'App/CMPRS.csproj',build/'App')
compile(root/'Installer/Setup.csproj',build/'Uninstaller','-p:Uninstaller=true')
stage=build/'Payload'
if stage.exists():shutil.rmtree(stage) # This directory is exclusively generated by this script.
shutil.copytree(build/'App',stage)
unused=stage/'Microsoft.Web.WebView2.Wpf.dll'
if unused.exists():unused.unlink()
shutil.copy2(build/'Uninstaller/Uninstall.exe',stage/'Uninstall.exe')
if (build/'Uninstaller/Uninstall.exe.config').exists():shutil.copy2(build/'Uninstaller/Uninstall.exe.config',stage/'Uninstall.exe.config')
(stage/'bin').mkdir()
with zipfile.ZipFile(root/'Dependencies/ffmpeg-7.1.1.zip') as archive:
 for name in ['ffmpeg.exe','ffprobe.exe']:
  source=next(n for n in archive.namelist() if n.endswith('/bin/'+name))
  (stage/'bin'/name).write_bytes(archive.read(source))
shutil.copy2(root/'Dependencies/MicrosoftEdgeWebview2Setup.exe',stage/'MicrosoftEdgeWebview2Setup.exe')
shutil.copytree(root/'Licenses',stage/'Licenses')
for name in ['LICENSE','NOTICE.md','README.md']:shutil.copy2(root/name,stage/name)
required=['CMPRS.exe','Uninstall.exe','WebView2Loader.dll','Microsoft.Web.WebView2.Core.dll','Microsoft.Web.WebView2.WinForms.dll','Newtonsoft.Json.dll','UI/app.js','UI/style.css','UI/index.html','bin/ffmpeg.exe','bin/ffprobe.exe']
for name in required:
 if not (stage/name).is_file():raise RuntimeError('Missing payload file: '+name)
files=sorted(p for p in stage.rglob('*') if p.is_file())
(stage/'SHA256SUMS.txt').write_text(''.join(digest(p)+'  '+p.relative_to(stage).as_posix()+'\n' for p in files),encoding='utf-8')
with zipfile.ZipFile(build/'Payload.zip','w',zipfile.ZIP_DEFLATED,compresslevel=6) as z:
 for p in sorted(stage.rglob('*')):
  if p.is_file():z.write(p,p.relative_to(stage).as_posix())
compile(root/'Installer/Setup.csproj',build/'Setup')
out=root.parent/'CMPRS-2.0.1-Windows-x64-Setup.exe'
shutil.copy2(build/'Setup/CMPRS-Setup.exe',out)
proof={'version':'2.0.1','platform':'Windows x64','setup':{'name':out.name,'bytes':out.stat().st_size,'sha256':digest(out)},
       'payloadFiles':required,'authenticodeSigned':False,'windowsRuntimeTested':False}
(root/'Verification/Artifacts.json').write_text(json.dumps(proof,indent=2))
print(json.dumps(proof,indent=2))
